-- 01_tables.sql
-- InvoiceGuard tables, constraints and indexes (SPEC section 1).
-- Standard audit columns on transactional tables. PKs are identity columns.

SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE

-- ---------------------------------------------------------------------------
-- Users (application users; not the database schema owner IG)
-- ---------------------------------------------------------------------------
CREATE TABLE ig_users (
  user_id          NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_users_pk PRIMARY KEY,
  user_name        VARCHAR2(30)  CONSTRAINT ig_users_name_uk UNIQUE NOT NULL
                                 CONSTRAINT ig_users_name_upper_ck CHECK (user_name = UPPER(user_name)),
  full_name        VARCHAR2(100) NOT NULL,
  role             VARCHAR2(20)  NOT NULL
                                 CONSTRAINT ig_users_role_ck CHECK (role IN ('AP_CLERK','AP_MANAGER','FIN_CONTROLLER','BUYER','RECEIVER','AUDITOR')),
  approval_limit   NUMBER(16,2)  DEFAULT 0 NOT NULL CONSTRAINT ig_users_limit_ck CHECK (approval_limit >= 0),
  active_flag      VARCHAR2(1)   DEFAULT 'Y' NOT NULL CONSTRAINT ig_users_active_ck CHECK (active_flag IN ('Y','N')),
  created_by       VARCHAR2(30)  DEFAULT USER NOT NULL,
  created_date     DATE          DEFAULT SYSDATE NOT NULL,
  last_updated_by  VARCHAR2(30),
  last_updated_date DATE
);

-- ---------------------------------------------------------------------------
-- Vendors and bank accounts
-- ---------------------------------------------------------------------------
CREATE TABLE ig_vendors (
  vendor_id          NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_vendors_pk PRIMARY KEY,
  vendor_num         VARCHAR2(20)  CONSTRAINT ig_vendors_num_uk UNIQUE NOT NULL,
  vendor_name        VARCHAR2(120) NOT NULL,
  gstin              VARCHAR2(15),
  pan                VARCHAR2(10),
  status             VARCHAR2(12)  DEFAULT 'ACTIVE' NOT NULL
                                   CONSTRAINT ig_vendors_status_ck CHECK (status IN ('ACTIVE','INACTIVE','BLOCKED')),
  payment_terms_days NUMBER(4)     DEFAULT 30 NOT NULL CONSTRAINT ig_vendors_terms_ck CHECK (payment_terms_days >= 0),
  risk_category      VARCHAR2(10)  DEFAULT 'LOW' NOT NULL
                                   CONSTRAINT ig_vendors_risk_ck CHECK (risk_category IN ('LOW','MEDIUM','HIGH')),
  created_by         VARCHAR2(30)  DEFAULT USER NOT NULL,
  created_date       DATE          DEFAULT SYSDATE NOT NULL,
  last_updated_by    VARCHAR2(30),
  last_updated_date  DATE
);

CREATE TABLE ig_vendor_bank_accts (
  bank_acct_id   NUMBER       GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_vba_pk PRIMARY KEY,
  vendor_id      NUMBER       NOT NULL CONSTRAINT ig_vba_vendor_fk REFERENCES ig_vendors(vendor_id),
  account_num    VARCHAR2(30) NOT NULL,
  ifsc           VARCHAR2(11) NOT NULL,
  effective_from DATE         DEFAULT SYSDATE NOT NULL,
  active_flag    VARCHAR2(1)  DEFAULT 'Y' NOT NULL CONSTRAINT ig_vba_active_ck CHECK (active_flag IN ('Y','N')),
  created_by     VARCHAR2(30) DEFAULT USER NOT NULL,
  created_date   DATE         DEFAULT SYSDATE NOT NULL
);
-- Only one active account per vendor (NULLs are not indexed, so inactive rows are unconstrained)
CREATE UNIQUE INDEX ig_vba_one_active_uk ON ig_vendor_bank_accts (CASE WHEN active_flag = 'Y' THEN vendor_id END);
CREATE INDEX ig_vba_account_ix ON ig_vendor_bank_accts (account_num);

-- ---------------------------------------------------------------------------
-- Purchase orders
-- ---------------------------------------------------------------------------
CREATE TABLE ig_po_headers (
  po_header_id  NUMBER       GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_po_headers_pk PRIMARY KEY,
  po_num        VARCHAR2(20) CONSTRAINT ig_po_headers_num_uk UNIQUE NOT NULL,
  vendor_id     NUMBER       NOT NULL CONSTRAINT ig_po_headers_vendor_fk REFERENCES ig_vendors(vendor_id),
  po_date       DATE         NOT NULL,
  currency      VARCHAR2(3)  DEFAULT 'INR' NOT NULL,
  status        VARCHAR2(12) DEFAULT 'OPEN' NOT NULL
                             CONSTRAINT ig_po_headers_status_ck CHECK (status IN ('OPEN','CLOSED','CANCELLED')),
  buyer_user    VARCHAR2(30) NOT NULL CONSTRAINT ig_po_headers_buyer_fk REFERENCES ig_users(user_name),
  created_by    VARCHAR2(30) DEFAULT USER NOT NULL,
  created_date  DATE         DEFAULT SYSDATE NOT NULL,
  last_updated_by VARCHAR2(30),
  last_updated_date DATE
);
CREATE INDEX ig_po_headers_vendor_ix ON ig_po_headers (vendor_id);
CREATE INDEX ig_po_headers_buyer_ix ON ig_po_headers (buyer_user);

CREATE TABLE ig_po_lines (
  po_line_id   NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_po_lines_pk PRIMARY KEY,
  po_header_id NUMBER        NOT NULL CONSTRAINT ig_po_lines_hdr_fk REFERENCES ig_po_headers(po_header_id),
  line_num     NUMBER(4)     NOT NULL,
  item_code    VARCHAR2(30)  NOT NULL,
  description  VARCHAR2(200),
  uom          VARCHAR2(10)  DEFAULT 'EA' NOT NULL,
  qty_ordered  NUMBER(14,3)  NOT NULL CONSTRAINT ig_po_lines_qty_ck CHECK (qty_ordered > 0),
  unit_price   NUMBER(16,2)  NOT NULL CONSTRAINT ig_po_lines_price_ck CHECK (unit_price >= 0),
  tax_rate     NUMBER(5,2)   DEFAULT 0 NOT NULL CONSTRAINT ig_po_lines_tax_ck CHECK (tax_rate >= 0),
  created_by   VARCHAR2(30)  DEFAULT USER NOT NULL,
  created_date DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT ig_po_lines_line_uk UNIQUE (po_header_id, line_num)
);
CREATE INDEX ig_po_lines_item_ix ON ig_po_lines (item_code);

-- ---------------------------------------------------------------------------
-- Goods receipts (GRN)
-- ---------------------------------------------------------------------------
CREATE TABLE ig_receipts (
  receipt_id   NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_receipts_pk PRIMARY KEY,
  receipt_num  VARCHAR2(20)  CONSTRAINT ig_receipts_num_uk UNIQUE NOT NULL,
  po_header_id NUMBER        NOT NULL CONSTRAINT ig_receipts_hdr_fk REFERENCES ig_po_headers(po_header_id),
  receipt_date DATE          DEFAULT SYSDATE NOT NULL,
  received_by  VARCHAR2(30)  NOT NULL CONSTRAINT ig_receipts_recv_fk REFERENCES ig_users(user_name),
  created_by   VARCHAR2(30)  DEFAULT USER NOT NULL,
  created_date DATE          DEFAULT SYSDATE NOT NULL
);
CREATE INDEX ig_receipts_hdr_ix ON ig_receipts (po_header_id);
CREATE INDEX ig_receipts_recv_ix ON ig_receipts (received_by);

CREATE TABLE ig_receipt_lines (
  receipt_line_id NUMBER      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_receipt_lines_pk PRIMARY KEY,
  receipt_id      NUMBER      NOT NULL CONSTRAINT ig_receipt_lines_rcpt_fk REFERENCES ig_receipts(receipt_id),
  po_line_id      NUMBER      NOT NULL CONSTRAINT ig_receipt_lines_pol_fk REFERENCES ig_po_lines(po_line_id),
  qty_received    NUMBER(14,3) NOT NULL CONSTRAINT ig_receipt_lines_qty_ck CHECK (qty_received >= 0),
  qty_rejected    NUMBER(14,3) DEFAULT 0 NOT NULL CONSTRAINT ig_receipt_lines_rej_ck CHECK (qty_rejected >= 0),
  created_by      VARCHAR2(30) DEFAULT USER NOT NULL,
  created_date    DATE         DEFAULT SYSDATE NOT NULL
);
CREATE INDEX ig_receipt_lines_rcpt_ix ON ig_receipt_lines (receipt_id);
CREATE INDEX ig_receipt_lines_pol_ix ON ig_receipt_lines (po_line_id);

-- ---------------------------------------------------------------------------
-- Supplier invoices
-- ---------------------------------------------------------------------------
CREATE TABLE ig_invoices (
  invoice_id         NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_invoices_pk PRIMARY KEY,
  vendor_id          NUMBER        NOT NULL CONSTRAINT ig_invoices_vendor_fk REFERENCES ig_vendors(vendor_id),
  invoice_num        VARCHAR2(40)  NOT NULL,
  invoice_num_norm   VARCHAR2(40),
  invoice_date       DATE          NOT NULL,
  received_date      DATE          DEFAULT SYSDATE NOT NULL,
  po_header_id       NUMBER        NOT NULL CONSTRAINT ig_invoices_po_fk REFERENCES ig_po_headers(po_header_id),
  currency           VARCHAR2(3)   DEFAULT 'INR' NOT NULL,
  exchange_rate      NUMBER(12,6)  DEFAULT 1 NOT NULL CONSTRAINT ig_invoices_fx_ck CHECK (exchange_rate > 0),
  invoice_amount     NUMBER(16,2)  NOT NULL,
  tax_amount         NUMBER(16,2)  DEFAULT 0 NOT NULL CONSTRAINT ig_invoices_tax_ck CHECK (tax_amount >= 0),
  base_amount        NUMBER(18,2),
  bank_acct_id       NUMBER        NOT NULL CONSTRAINT ig_invoices_bank_fk REFERENCES ig_vendor_bank_accts(bank_acct_id),
  status             VARCHAR2(12)  DEFAULT 'DRAFT' NOT NULL
                                   CONSTRAINT ig_invoices_status_ck CHECK (status IN ('DRAFT','ON_HOLD','VALIDATED','APPROVED','REJECTED','PAID','CANCELLED')),
  risk_score         NUMBER        DEFAULT 0 NOT NULL CONSTRAINT ig_invoices_risk_ck CHECK (risk_score BETWEEN 0 AND 100),
  entered_by         VARCHAR2(30),
  approved_by        VARCHAR2(30),
  approved_date      DATE,
  payment_ref        VARCHAR2(60),
  paid_date          DATE,
  description        VARCHAR2(400),
  created_by         VARCHAR2(30)  DEFAULT USER NOT NULL,
  created_date       DATE          DEFAULT SYSDATE NOT NULL,
  last_updated_by    VARCHAR2(30),
  last_updated_date  DATE
);
CREATE INDEX ig_invoices_vendor_ix ON ig_invoices (vendor_id);
CREATE INDEX ig_invoices_po_ix ON ig_invoices (po_header_id);
CREATE INDEX ig_invoices_bank_ix ON ig_invoices (bank_acct_id);
CREATE INDEX ig_invoices_vendor_norm_ix ON ig_invoices (vendor_id, invoice_num_norm);
CREATE INDEX ig_invoices_vendor_date_ix ON ig_invoices (vendor_id, invoice_date);

CREATE TABLE ig_invoice_lines (
  invoice_line_id NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_invoice_lines_pk PRIMARY KEY,
  invoice_id      NUMBER        NOT NULL CONSTRAINT ig_invoice_lines_inv_fk REFERENCES ig_invoices(invoice_id) ON DELETE CASCADE,
  line_num        NUMBER(4)     NOT NULL,
  po_line_id      NUMBER        NOT NULL CONSTRAINT ig_invoice_lines_pol_fk REFERENCES ig_po_lines(po_line_id),
  qty_billed      NUMBER(14,3)  NOT NULL CONSTRAINT ig_invoice_lines_qty_ck CHECK (qty_billed > 0),
  unit_price      NUMBER(16,2)  NOT NULL CONSTRAINT ig_invoice_lines_price_ck CHECK (unit_price >= 0),
  line_amount     NUMBER(18,2),
  created_by      VARCHAR2(30)  DEFAULT USER NOT NULL,
  created_date    DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT ig_invoice_lines_line_uk UNIQUE (invoice_id, line_num)
);
CREATE INDEX ig_invoice_lines_pol_ix ON ig_invoice_lines (po_line_id);

-- ---------------------------------------------------------------------------
-- Reference data: hold codes and settings
-- ---------------------------------------------------------------------------
CREATE TABLE ig_hold_codes (
  hold_code    VARCHAR2(20)  CONSTRAINT ig_hold_codes_pk PRIMARY KEY,
  description  VARCHAR2(200) NOT NULL,
  severity     VARCHAR2(6)   NOT NULL CONSTRAINT ig_hold_codes_sev_ck CHECK (severity IN ('HIGH','MEDIUM','LOW')),
  risk_weight  NUMBER(4)     NOT NULL CONSTRAINT ig_hold_codes_wt_ck CHECK (risk_weight >= 0),
  release_role VARCHAR2(20)  CONSTRAINT ig_hold_codes_role_ck CHECK (release_role IN ('AP_CLERK','AP_MANAGER','FIN_CONTROLLER','BUYER','RECEIVER','AUDITOR')),
  category     VARCHAR2(12)  NOT NULL CONSTRAINT ig_hold_codes_cat_ck CHECK (category IN ('MATCH','DUPLICATE','FRAUD','COMPLIANCE','AUTHORITY'))
);

CREATE TABLE ig_settings (
  param_name  VARCHAR2(40)  CONSTRAINT ig_settings_pk PRIMARY KEY,
  num_value   NUMBER(18,4)  NOT NULL,
  description VARCHAR2(200)
);

-- ---------------------------------------------------------------------------
-- Holds, approval history, audit
-- ---------------------------------------------------------------------------
CREATE TABLE ig_invoice_holds (
  hold_id        NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_invoice_holds_pk PRIMARY KEY,
  invoice_id     NUMBER        NOT NULL CONSTRAINT ig_invoice_holds_inv_fk REFERENCES ig_invoices(invoice_id),
  invoice_line_id NUMBER       CONSTRAINT ig_invoice_holds_line_fk REFERENCES ig_invoice_lines(invoice_line_id),
  hold_code      VARCHAR2(20)  NOT NULL CONSTRAINT ig_invoice_holds_code_fk REFERENCES ig_hold_codes(hold_code),
  hold_reason    VARCHAR2(400) NOT NULL,
  hold_date      DATE          DEFAULT SYSDATE NOT NULL,
  status         VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL CONSTRAINT ig_invoice_holds_status_ck CHECK (status IN ('OPEN','RELEASED')),
  released_by    VARCHAR2(30),
  release_date   DATE,
  release_reason VARCHAR2(400),
  created_by     VARCHAR2(30)  DEFAULT USER NOT NULL,
  created_date   DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT ig_invoice_holds_rel_ck CHECK (status = 'OPEN' OR release_date IS NOT NULL)
);
CREATE INDEX ig_invoice_holds_inv_ix ON ig_invoice_holds (invoice_id);
CREATE INDEX ig_invoice_holds_line_ix ON ig_invoice_holds (invoice_line_id);
CREATE INDEX ig_invoice_holds_code_ix ON ig_invoice_holds (hold_code);
CREATE INDEX ig_invoice_holds_status_ix ON ig_invoice_holds (status, hold_code);

CREATE TABLE ig_approval_history (
  approval_id  NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_approval_history_pk PRIMARY KEY,
  invoice_id   NUMBER        NOT NULL CONSTRAINT ig_approval_history_inv_fk REFERENCES ig_invoices(invoice_id),
  user_name    VARCHAR2(30),
  action       VARCHAR2(20)  NOT NULL CONSTRAINT ig_approval_history_act_ck CHECK (action IN ('APPROVE','REJECT','RELEASE_HOLD','CANCEL','PAY','SCAN')),
  outcome      VARCHAR2(10)  NOT NULL CONSTRAINT ig_approval_history_out_ck CHECK (outcome IN ('SUCCESS','BLOCKED')),
  reason       VARCHAR2(400),
  action_date  DATE          DEFAULT SYSDATE NOT NULL
);
CREATE INDEX ig_approval_history_inv_ix ON ig_approval_history (invoice_id);

CREATE TABLE ig_audit_log (
  audit_id     NUMBER        GENERATED BY DEFAULT AS IDENTITY CONSTRAINT ig_audit_log_pk PRIMARY KEY,
  entity_name  VARCHAR2(30)  NOT NULL,
  entity_id    VARCHAR2(60),
  action       VARCHAR2(30)  NOT NULL,
  old_value    VARCHAR2(4000),
  new_value    VARCHAR2(4000),
  user_name    VARCHAR2(30),
  action_ts    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ig_audit_log_entity_ix ON ig_audit_log (entity_name, entity_id);

SET DEFINE OFF
PROMPT Tables created.
